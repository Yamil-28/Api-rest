  fecha_expira timestamptz NOT NULL DEFAULT (now() + interval '10 minutes'),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_cofre_attempt_charge ON public.cofre_payment_attempts(cargo_id);
